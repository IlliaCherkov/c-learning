#include <stdio.h>

int main(void)
{
  printf("Hello, World!\n"); // /n new line like (ENTER)
  printf("VIN SKAZAV: \"Pryvit\"\n"); // \" quote symbol inside text
  printf("r9dok1\nr9dok 2\n");  // /n new line like (ENTER)
  printf("shl9h u Windows: C:\\USERS\\CHRKV\n"); // \\ one backslash symbol
  printf("kolonka1\tKolonka2\tKolonka3\n"); //// \t tab(big space, aligns columns)
  return 0;
}
  
// \n  - new l i n //e (перенос рядка)
// \t  - tab (табуляція, відступ)
// \"  - double quote (лапки всередині тексту)
// \'  - single quote (одинарна лапка)
// \\  - backslash (сама коса риска)
// \r  - carriage return (курсор на початок рядка)
// \0  - null terminator (кінець рядка в C - вивчиш пізніше!)



